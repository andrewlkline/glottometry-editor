    M, langs, inns = load_matrix(path)
    print(f"{len(inns)} innovations x {len(langs)} languages "
          f"({int(np.isnan(M).sum())} NA cells)")

    g = Glottometry(M, langs)
    df = g.subgroups()
    print(f"{len(df)} attested subgroups\n")

    print(f"{'sigma':>7} {'kappa':>6} {'eps':>6}  members")
    for _, r in df.head(12).iterrows():
        print(f"{r.sigma:7.2f} {r.kappa:6.2f} {r.epsilon:6.2f}  {'+'.join(r.members)}")

    shown = df[df.sigma >= 1.0]
    order, cost = seriate(list(shown['mask']), list(shown.sigma), len(langs))
    contiguous = sum(1 for m in shown['mask'] if _breaks(order, m) == 0)
    print(f"\nlayout: {contiguous}/{len(shown)} of the sigma>=1 subgroups are "
          f"contiguous (weighted break cost {cost:.2f})")
    print("order:", " ".join(langs[i] for i in order))
